# Tipos int e float
# int -> Numero interio
# O tipo int representa qualquer numero
# positivo ou negativo. int sem sinal é considerado positivo.

# print(444) #int
# print(-444) #int
# print(0) #int




# float -> Numero com ponto flutuante
# O tipo float repre4senta qualquer numeri
# positivo ou negativo com ponto flutuante
# float sem sinal e considerado positivo


# print(4.44) #float
# print(-4.44) #float
# print(0.0, 1.44) #float

# A função type mostra o tipo em Python inferiou ao valor
print(type(444)) #int
print(type('Aprender Python')) #str 
print(type(-4.44), type(0.0)) #float         